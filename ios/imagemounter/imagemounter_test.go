package imagemounter

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestName(t *testing.T) {
	in := []byte{0x37, 0x15, 0x83, 0x65, 0x6b, 0x19, 0x23, 0x24, 0x40, 0x35, 0xff, 0x02, 0x8d, 0xce, 0x6a, 0x6d}
	expected := []byte{0x15, 0x37, 0x65, 0x83, 0x19, 0x6b, 0x24, 0x23, 0x35, 0x40, 0x02, 0xff, 0xce, 0x8d, 0x6d, 0x6a}

	err := flip(in)
	require.NoError(t, err)
	assert.Equal(t, in, expected)
}
